"""Verified gap report of the forms catalogue (owner's direction 2026-10-21, docs/forms-catalogue/DIRECTION-2026-10-21-REGISTER-FIRST.md §4).

write(repo, rows, checks) writes docs/forms-catalogue/GAP-REPORT.md and docs/forms-catalogue/gap-report.json from the register's
catalogue rows (catalogue.py) and an independent re-read of every JSON contract in the source files. Generated by
app/scripts/requirements/extract.py; never edited by hand. The JSON carries the SHA-256 of every source and of the scope list,
so app/src/lib/requirements/requirements.test.ts fails when the report is stale.
"""
import collections, hashlib, json, os, re
import catalogue as C

OUT_MD = 'docs/forms-catalogue/GAP-REPORT.md'
OUT_JSON = 'docs/forms-catalogue/gap-report.json'
REPORTED = {'listed forms, parts 14–22': 216, 'contracts, parts 14–22': 61, 'core contracts, parts 5–13': 72}
# What each controlled batch of CivicOS's own contracts covers (owner's approvals, 21 October 2026).
BATCH_LABEL = {1: 'health regulation', 2: 'medicines and medical devices regulation', 3: 'taxpayer registration and account'}
GATES = [
    'The form owner and competent authority are verified.',
    'Legal references and their versions have been approved.',
    'Required fields and validation rules pass automated tests.',
    'Data sources are authoritative or explicitly labelled otherwise.',
    'Access controls and restricted-record audit tests pass.',
    'Workflow and decision permissions pass negative tests.',
    'Accessibility and localization tests pass.',
    'Retention and correction rules are approved.',
    'Release and rollback plans are recorded.',
    'The production approver is distinct from the proposer wherever separation of duties is required.',
]
PLACEHOLDER = re.compile(r'\$\{[^}]+\}|approved-|configured-')


def sha(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest()


def contracts(repo):
    """Every JSON contract in the source files: (source, line, id, kind, fields, legal_basis)."""
    out = []
    for rel, tag in C.FILES:
        lines = open(os.path.join(repo, rel), encoding='utf-8').read().split('\n')
        i = 0
        while i < len(lines):
            if lines[i] == '{':
                j = i
                while lines[j] != '}':
                    j += 1
                obj = json.loads('\n'.join(lines[i:j + 1]))
                block = lines[i:j + 1]

                def line_of(pat):
                    return next((i + 1 + k for k, l in enumerate(block) if pat in l), i + 1)
                if 'contracts' in obj:
                    for c in obj['contracts']:
                        out.append(dict(source=rel, line=line_of(f'"form_id": "{c.get("form_id")}"'), id=c.get('form_id'), kind='form',
                                        fields=c.get('fields', []), legal_basis=c.get('legal_basis'), part=None))
                elif 'fields' in obj:
                    cid = obj.get('form_id') or obj.get('group_id')
                    out.append(dict(source=rel, line=i + 1, id=cid, kind='group' if obj.get('group_id') else 'form', fields=obj['fields'],
                                    legal_basis=obj.get('legal_basis'), version=obj.get('version')))
                i = j
            i += 1
    return out


def build(repo, rows, checks):
    scope = C.load_scope(repo)
    non_form = {(e['source'], e['id']): e['reason'] for e in scope.get('non_form_contracts', [])}
    forms = [o for o in rows if o['category'] == 'form']
    groups = [o for o in rows if o['category'] == 'field group']
    sup = 'docs/forms-catalogue/SUPPLEMENT-PARTS-14-22-AND-CONTRACTS-05-13.md'
    # 1. unique form IDs
    ids = sorted({o['catalogue_id'] for o in forms})
    by_part = collections.Counter()
    for o in forms:
        by_part[C.part_label(o)] += 1
    # 2. contracts matched to forms
    cs = contracts(repo)
    matches, unmatched, ambiguous = [], [], []
    for c in cs:
        if (c['source'], c['id']) in non_form:
            matches.append(dict(c, match='not a form', reason=non_form[(c['source'], c['id'])]))
            continue
        if c['kind'] == 'group':
            # a field-group contract defines its group (part 1 §1.2 'Group N — …'); matched to the group's ID row where the text gives one
            g = [o for o in groups if o['source'] == c['source'] and o['catalogue_id'] == f"{c['id']}.v{c.get('version', 1)}"]
            matches.append(dict(c, match=g[0]['id'] if g else f"group {c['id']} (defined by its contract)"))
            continue
        same = [o for o in forms if o['source'] == c['source'] and o['catalogue_id'] == c['id']]
        cand = same or [o for o in forms if o['catalogue_id'] == c['id'] and c['id'] not in checks['collisions']]
        if len(cand) == 1:
            matches.append(dict(c, match=cand[0]['id']))
        elif not cand:
            unmatched.append(dict(c, match=None))
        else:
            ambiguous.append(dict(c, match=[o['id'] for o in cand]))
    form_contracts = collections.Counter(m['match'] for m in matches if m.get('match') and m['kind'] == 'form' and m['match'] != 'not a form')
    # contracts in the supplement by stage (parts 14-22 vs Stage B 5-13), by the form they match
    row_by_id = {o['id']: o for o in rows}
    # where each supplement contract stands (its own place in the file, not its form's)
    where = {(o['source'], int(o['lines'].split('-')[0])): o['part'] for o in rows if o['kind'] == 'contract'}
    stage = collections.Counter()
    for m in matches:
        if m['source'] == sup and m['kind'] == 'form':
            p = where.get((m['source'], m['line']), 0)
            stage['parts 14–22' if p >= 14 else ('parts 5–13' if p >= 5 else 'shared standard')] += 1
    # 3. forms without a contract; incomplete contracts; duplicates
    no_contract = [o for o in forms if o['contract'] not in C.CONTRACT_GIVEN]
    # CivicOS's own contracts (the form library, controlled batches): each matched to exactly one registered form, none in an excluded or legal-review scope
    lib = checks.get('library', [])
    lib_bad = [dict(path=c['path'], id=c['id'], matches=c['matches']) for c in lib if len(c['matches']) != 1]
    row_of = {o['id']: o for o in forms}
    batches = collections.OrderedDict()
    for c in lib:
        b = batches.setdefault(c['batch'], dict(batch=c['batch'], contracts=[], form_status=collections.Counter()))
        r = row_of.get(c['matches'][0]) if len(c['matches']) == 1 else None
        b['contracts'].append(dict(id=c['id'], row=c['matches'][0] if r else None, file=c['path'], fields=len(c['fields']), form_status=r['form_status'] if r else None, scope=(r or {}).get('scope', 'allowed')))
        if r:
            b['form_status'][r['form_status']] += 1
    # the register as it stood before CivicOS's contracts: the same forms, without the library (a library contract is the only thing that moved them),
    # and after each batch in turn
    moved = lambda o, upto: o['contract'] == C.LIBRARY_GIVEN and o['form_status'] in ('contract_draft', 'blocked') and batch_of.get(o['id'], 0) > upto
    batch_of = {c['matches'][0]: c['batch'] for c in lib if len(c['matches']) == 1}
    before = collections.Counter('contract_missing' if moved(o, 0) else o['form_status'] for o in forms)
    after_batch = {b: collections.Counter('contract_missing' if moved(o, b) else o['form_status'] for o in forms) for b in sorted(batches)}
    incomplete = []
    for c in cs:
        if (c['source'], c['id']) in non_form:
            continue
        missing_tr = [f.get('id') or f.get('field_id') or f.get('key') for f in c['fields'] if 'type' not in f or 'required' not in f]
        lb = c.get('legal_basis')
        lb_state = 'none in the contract' if not lb else ('placeholders only' if PLACEHOLDER.search(json.dumps(lb)) else 'given')
        if missing_tr or lb_state != 'given':
            incomplete.append(dict(source=c['source'], line=c['line'], id=c['id'], kind=c['kind'], fields=len(c['fields']),
                                   fields_missing_type_or_required=missing_tr, legal_basis=lb_state))
    dup_ids = checks['collisions']
    titles = collections.defaultdict(set)
    for o in forms:
        t = re.sub(r'\W+', ' ', (next((v for k, v in (o.get('cells') or {}).items() if re.search(r'form|name|title|purpose', k, re.I) and v != o['catalogue_id']), '') or '').lower()).strip()
        if t:
            titles[(t, o['catalogue_id'].split('-')[0].split('.')[0])].add(o['catalogue_id'])
    same_form = {f'{t} [{p}]': sorted(v) for (t, p), v in titles.items() if len(v) > 1}
    # 4. scope
    viol = []
    for o in forms:
        if o['form_status'] in ('excluded', 'under_review') and o['contract'] in C.CONTRACT_GIVEN:
            viol.append(dict(id=o['id'], source=o['source'], form_status=o['form_status'], flag=o.get('scope_flag'), why='a contract was given for a form outside the approved scope'))
        if o['form_status'] == 'blocked':
            viol.append(dict(id=o['id'], source=o['source'], form_status='blocked', flag=o.get('scope_flag'), why=o.get('blocked_by')))
    legal = [o for o in forms if o['form_status'] == 'under_review']
    prod = [o for o in forms if o['form_status'] in ('approved', 'production')]
    fs = collections.Counter(o['form_status'] for o in forms)
    verified = {
        'listed forms, parts 14–22': len({o['catalogue_id'] for o in forms if o['source'] == sup and o['part'] >= 14}),
        'contracts, parts 14–22': stage['parts 14–22'],
        'core contracts, parts 5–13': stage['parts 5–13'],
    }
    rep = dict(
        generated_by='app/scripts/requirements/extract.py (gap_report.py)',
        sources={rel: sha(os.path.join(repo, rel)) for rel, _ in C.FILES} | {C.SCOPE: sha(os.path.join(repo, C.SCOPE))} | {c['path']: sha(os.path.join(repo, c['path'])) for c in lib},
        reported=REPORTED, verified=verified,
        unique_form_ids=len(ids), form_rows=len(forms), forms_by_part=dict(by_part),
        form_status=dict(fs),
        contracts=dict(total=len(cs), matched_to_one_form=sum(1 for m in matches if m['kind'] == 'form' and m['match'] != 'not a form'),
                       field_groups=sum(1 for m in matches if m['kind'] == 'group'), not_a_form=[dict(source=m['source'], id=m['id'], reason=m['reason']) for m in matches if m.get('match') == 'not a form'],
                       unmatched=[dict(source=c['source'], line=c['line'], id=c['id']) for c in unmatched],
                       ambiguous=[dict(source=c['source'], line=c['line'], id=c['id'], candidates=c['match']) for c in ambiguous],
                       forms_with_more_than_one=[k for k, v in form_contracts.items() if v > 1]),
        forms_without_contract=len(no_contract),
        library_contracts=dict(total=len(lib), matched_to_one_form=len(lib) - len(lib_bad), unmatched_or_ambiguous=lib_bad,
                               batches=[dict(b, form_status=dict(b['form_status'])) for b in batches.values()],
                               form_status_without_library=dict(before), forms_without_contract_without_library=len(no_contract) + sum(1 for o in forms if o['contract'] == C.LIBRARY_GIVEN),
                               form_status_after_batch={str(b): dict(v) for b, v in after_batch.items()},
                               forms_without_contract_after_batch={str(b): len(no_contract) + sum(1 for o in forms if o['contract'] == C.LIBRARY_GIVEN and batch_of.get(o['id'], 0) > b) for b in after_batch}),
        incomplete_contracts=incomplete,
        duplicate_ids=dup_ids, same_title_different_ids=same_form,
        scope_violations=viol,
        legal_review=[dict(id=o['id'], source=o['source'], flag=o.get('scope_flag')) for o in legal],
        production_candidates=[o['id'] for o in prod],
        gates=GATES,
    )
    return rep, no_contract


def write(repo, rows, checks):
    rep, no_contract = build(repo, rows, checks)
    with open(os.path.join(repo, OUT_JSON), 'w', encoding='utf-8') as f:
        json.dump(rep, f, indent=1, ensure_ascii=False)
        f.write('\n')
    md = ['# Forms catalogue — verified gap report\n',
          'Generated by `python3 -I app/scripts/requirements/extract.py .` (`app/scripts/requirements/gap_report.py`) from the register\'s catalogue rows '
          '(`docs/requirements/requirements.json`), the scope list (`docs/requirements/form-scope.json`) and an independent re-read of every JSON contract in '
          'the source files. Never edited by hand: `app/src/lib/requirements/requirements.test.ts` fails when it is stale (source hashes in `gap-report.json`). '
          'Owner\'s direction 2026-10-21 (`DIRECTION-2026-10-21-REGISTER-FIRST.md` §4): no further batch of contracts until this report and the register agree.\n',
          '## Reported and verified figures\n', '| Figure | Reported | Verified |\n|---|---|---|']
    for k, v in REPORTED.items():
        md.append(f'| {k} | {v} | {rep["verified"][k]} |')
    md.append(f'\n**Unique form IDs across all 22 parts:** {rep["unique_form_ids"]} ({rep["form_rows"]} form rows; an ID recurring in another place is a row of its own).\n')
    md.append('| Part | Form rows |\n|---|---|')
    for k, v in rep['forms_by_part'].items():
        md.append(f'| {k} | {v} |')
    md.append('\n## Form status (one per form)\n')
    md.append('Derived from the files and the scope list; nothing in the catalogue is approved or in production. A missing contract is never an empty, approved or complete form.\n')
    md.append('| Status | Forms |\n|---|---|')
    for s in C.FORM_STATUSES:
        md.append(f'| {s} | {rep["form_status"].get(s, 0)} |')
    c = rep['contracts']
    md.append(f'\n## Contracts matched to forms\n\n{c["total"]} JSON contracts: {c["matched_to_one_form"]} matched to exactly one registered form, '
              f'{c["field_groups"]} field-group contracts matched to their group, {len(c["not_a_form"])} declared not a form, '
              f'{len(c["unmatched"])} unmatched, {len(c["ambiguous"])} ambiguous.\n')
    for x in c['not_a_form']:
        md.append(f'- Not a form: `{x["id"]}` ({x["source"].split("/")[-1]}): {x["reason"]}')
    for x in c['unmatched']:
        md.append(f'- Unmatched: `{x["id"]}` ({x["source"].split("/")[-1]} line {x["line"]})')
    for x in c['ambiguous']:
        md.append(f'- Ambiguous: `{x["id"]}` ({x["source"].split("/")[-1]} line {x["line"]}): {", ".join(x["candidates"])}')
    if c['forms_with_more_than_one']:
        md.append('- Forms with more than one contract (the shared standard\'s example and the part\'s own): ' + ', '.join(f'`{x}`' for x in c['forms_with_more_than_one']))
    lc = rep['library_contracts']
    md.append(f'\n## Contracts CivicOS wrote (form library, controlled batches)\n\n{lc["total"]} contracts in `app/src/lib/forms/library/catalogue-contracts/`, '
              f'{lc["matched_to_one_form"]} matched to exactly one registered form (by source file and catalogue ID, and by line where the catalogue repeats an ID in one file), {len(lc["unmatched_or_ambiguous"])} unmatched or ambiguous. '
              'Each is a contract draft: nothing in it is approved, and its publication gates (`lib/forms/publication.ts`) decide everything after that.\n')
    for b in lc['batches']:
        md.append(f'\n**Batch {b["batch"]}** ({BATCH_LABEL.get(b["batch"], "controlled batch")}, owner approved 21 October 2026): {len(b["contracts"])} contracts added; form status '
                  + ', '.join(f'{k} {v}' for k, v in sorted(b['form_status'].items())) + '.\n')
        md.append('| Form | Register row | Fields | Form status | Scope |\n|---|---|---|---|---|')
        for x in b['contracts']:
            md.append(f'| {x["id"]} | {x["row"] or "—"} | {x["fields"]} | {x["form_status"] or "—"} | {x["scope"]} |')
    md.append('\n**Totals beside the earlier ones** (the register without the library\'s contracts, after each batch, and now):\n')
    bs = list(lc['form_status_after_batch'])
    md.append('| Status | Before (without the library) | ' + ' | '.join(f'After batch {b}' for b in bs) + ' | Now |\n|---|---|' + '---|' * len(bs) + '---|')
    for s in C.FORM_STATUSES:
        md.append(f'| {s} | {lc["form_status_without_library"].get(s, 0)} | ' + ''.join(f'{lc["form_status_after_batch"][b].get(s, 0)} | ' for b in bs) + f'{rep["form_status"].get(s, 0)} |')
    md.append(f'| forms without a contract | {lc["forms_without_contract_without_library"]} | ' + ''.join(f'{lc["forms_without_contract_after_batch"][b]} | ' for b in bs) + f'{rep["forms_without_contract"]} |')
    md.append(f'\n## Forms with no contract\n\n{rep["forms_without_contract"]} forms have no field contract (`contract: not yet given` in the register). By part:\n')
    cnt = collections.Counter(C.part_label(o) for o in no_contract)
    md.append('| Part | Forms without a contract |\n|---|---|')
    for k, v in cnt.items():
        md.append(f'| {k} | {v} |')
    md.append(f'\n## Incomplete contracts ({len(rep["incomplete_contracts"])} of {c["total"]})\n')
    md.append('A contract is incomplete when a field lacks `type` or `required`, or the contract has no legal basis of its own that is not a placeholder.\n')
    md.append('| Contract | Source line | Fields | Fields without type or required | Legal basis |\n|---|---|---|---|---|')
    for x in rep['incomplete_contracts']:
        md.append(f'| {x["id"]} | {x["source"].split("/")[-1]} {x["line"]} | {x["fields"]} | {", ".join(x["fields_missing_type_or_required"]) or "—"} | {x["legal_basis"]} |')
    md.append(f'\n## Duplicate IDs\n\n**The same ID for different forms ({len(rep["duplicate_ids"])}):**\n')
    md.append('| ID | Occurrences |\n|---|---|')
    for k, v in sorted(rep['duplicate_ids'].items()):
        md.append(f'| {k} | ' + '; '.join(f'{f}: {t}' for f, t in v) + ' |')
    md.append(f'\n**The same title under different IDs in one domain prefix ({len(rep["same_title_different_ids"])}; possibly the same form, to be reviewed):**\n')
    md.append('| Title [prefix] | IDs |\n|---|---|')
    for k, v in sorted(rep['same_title_different_ids'].items()):
        md.append(f'| {k} | {", ".join(v)} |')
    md.append(f'\n## Contracts violating the approved scope ({len(rep["scope_violations"])})\n')
    md.append('| Form | Source | Status | Flag | Why |\n|---|---|---|---|---|')
    for x in rep['scope_violations']:
        md.append(f'| {x["id"]} | {x["source"].split("/")[-1]} | {x["form_status"]} | {x["flag"] or "—"} | {x["why"]} |')
    md.append(f'\n## Forms requiring legal review before implementation ({len(rep["legal_review"])})\n')
    md.append(', '.join(f'`{x["id"]}`' for x in rep['legal_review']) + '\n')
    md.append(f'\n## Production candidates and their gates\n\nProduction candidates: {len(rep["production_candidates"])} (expected: none). No form has passed any gate; '
              'every form must pass each of these before production (supplement, "Require production activation gates"), and the human approvals among them '
              'cannot be set by changing a status field (direction §3):\n')
    for k, g in enumerate(GATES, 1):
        md.append(f'{k}. {g} — passed by 0 forms.')
    open(os.path.join(repo, OUT_MD), 'w', encoding='utf-8').write('\n'.join(md) + '\n')
    return rep
