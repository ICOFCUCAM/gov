// Where a figure comes from — the first piece of the national digital twin
// (docs/INTEGRATION_REGISTER.md §16). Every number the console shows is a
// signal: its value plus what kind of figure it is and its source. Anything
// not observed is marked on screen, so a generated or modelled number is never
// read as a fact about the nation (the rule the public sites already follow).
//
//   observed    measured by a connected source (telemetry, a register)
//   reported    stated by an official record of the platform (the nation
//               profile, the ministry registry, the audit chain)
//   modelled    computed by an engine from other signals
//   sample      generated by the reference model until a source is connected
//   unavailable no source connected; no value is shown

export type SignalKind = 'observed' | 'reported' | 'modelled' | 'sample' | 'unavailable';

export interface Signal<T = number | string> {
  value: T | null;
  unit?: string;
  kind: SignalKind;
  /** Where it comes from, in words (a stream, a register, "Reference model"). */
  source: string;
  /** When it was true (ISO time), for observed and reported figures. */
  asOf?: string;
}

export const SIGNAL_LABEL: Record<SignalKind, string> = {
  observed: 'Observed',
  reported: 'Reported',
  modelled: 'Modelled',
  sample: 'Sample',
  unavailable: 'Not connected',
};

/** The reference model's generated figures: labelled as samples wherever they appear. */
export const REFERENCE_MODEL = 'Reference model (generated until a source is connected)';

export const sample = <T,>(value: T, unit?: string, source = REFERENCE_MODEL): Signal<T> => ({ value, unit, kind: 'sample', source });
export const modelled = <T,>(value: T, source: string, unit?: string): Signal<T> => ({ value, unit, kind: 'modelled', source });
export const reported = <T,>(value: T, source: string, unit?: string, asOf?: string): Signal<T> => ({ value, unit, kind: 'reported', source, ...(asOf ? { asOf } : {}) });
export const unavailable = (source: string, unit?: string): Signal<never> => ({ value: null, unit, kind: 'unavailable', source });

/** Whether a figure needs a marker on screen (everything that is not a measurement or an official record). */
export const needsMarker = (kind: SignalKind | undefined): boolean => kind !== 'observed' && kind !== 'reported';
