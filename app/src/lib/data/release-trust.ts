// The publisher keys a nation trusts for its software (plan I9; acceptance
// P5-15). A nation verifies signed releases and update media only with keys
// it chose to trust: one official proposes a key (its public half, and how
// its fingerprint was checked out of band: a call, a letter, the contract's
// annex), a different official confirms it (dualControlRefusal(), comparing
// people), and only then does anything it signed verify here. A newer key
// retires the earlier one, which still verifies what it signed before; one
// official revokes a key at once (it only takes trust away). Every step is in
// the audit chain; every version is kept. A production installation never
// trusts the development key a process generates for itself.
//
// Kept as it stands by a data restore (lib/backup/state.ts KEPT_ON_RESTORE):
// a restore must never bring back trust in a key revoked since.

import { randomUUID } from 'node:crypto';
import { touch } from '@/lib/data/repo/track';
import { withDefaults } from '@/lib/data/defaults';
import { recordAudit } from '@/lib/data/store/audit';
import { dualControlRefusal, independenceOf, dualControlPendingHours } from '@/lib/data/dual-control';
import { keyIdOfPem } from '@/lib/crypto/signing-key';
import { installationMode } from '@/lib/ops/mode';
import { releaseKey, type TrustedKey } from '@/lib/updates/release-signing';

export interface PublisherKey {
  id: string;
  nationId: string;
  keyId: string;
  publicKeyPem: string;
  /** How the fingerprint was checked with the publisher, out of band. */
  checkedWith: string;
  state: 'proposed' | 'trusted' | 'retired' | 'revoked' | 'withdrawn' | 'lapsed';
  proposed: { by: string; byId?: string; at: string };
  confirmed?: { by: string; byId?: string; at: string; independence: ReturnType<typeof independenceOf> };
  retiredAt?: string;
  revoked?: { by: string; at: string; reason: string };
}
type Db = { keys: PublisherKey[] };
const seed = (): Db => ({ keys: [] });
const g = globalThis as unknown as { __civicosReleaseTrust?: Db };
const db = (): Db => touch('__civicosReleaseTrust', g.__civicosReleaseTrust = withDefaults(g.__civicosReleaseTrust ??= seed(), seed()));
export function resetReleaseTrust(): void { g.__civicosReleaseTrust = undefined; }
const fail = (error: string, status = 422) => ({ error, status });
const res = (nationId: string) => `UpdateChamber:${nationId}/publisher-keys`;
export interface TrustActor { by: string; byId?: string }

function lapse(now: Date): void {
  for (const k of db().keys) if (k.state === 'proposed' && now.getTime() - Date.parse(k.proposed.at) > dualControlPendingHours() * 3_600_000) {
    k.state = 'lapsed';
    recordAudit('System (dual control)', 'update.publisher-key.lapse', res(k.nationId), 'ok', `${k.keyId}: not confirmed in time`);
  }
}

/** A nation's publisher keys, newest first (every state kept). */
export function publisherKeys(nationId: string, now = new Date()): PublisherKey[] { lapse(now); return db().keys.filter(k => k.nationId === nationId).map(k => structuredClone(k)).reverse(); }

/** One official proposes trusting a publisher key, saying how its fingerprint was checked. */
export function proposePublisherKey(nationId: string, input: { publicKeyPem?: unknown; checkedWith?: unknown }, actor: TrustActor, now = new Date()): PublisherKey | { error: string; status: number } {
  lapse(now);
  const pem = typeof input.publicKeyPem === 'string' ? input.publicKeyPem.trim() : '';
  const keyId = pem ? keyIdOfPem(pem) : null;
  if (!keyId) return fail('Send the publisher\'s public key as an Ed25519 SPKI PEM (-----BEGIN PUBLIC KEY-----)');
  const checkedWith = typeof input.checkedWith === 'string' ? input.checkedWith.trim().slice(0, 300) : '';
  if (checkedWith.length < 10) return fail('Say how the key\'s fingerprint was checked with the publisher, out of band (a call to a known number, a signed letter, the contract\'s annex)');
  if (installationMode() === 'production') { const dev = releaseKey(); if (!dev.production && dev.keyId === keyId) return fail('This is a development key generated by a process: a production installation never trusts it'); }
  if (db().keys.some(k => k.nationId === nationId && k.keyId === keyId && ['proposed', 'trusted'].includes(k.state))) return fail('This key is already trusted or waiting for confirmation', 409);
  const k: PublisherKey = { id: `PUB-${randomUUID().slice(0, 8)}`, nationId, keyId, publicKeyPem: pem, checkedWith, state: 'proposed', proposed: { by: actor.by, ...(actor.byId ? { byId: actor.byId } : {}), at: now.toISOString() } };
  db().keys.push(k);
  recordAudit(actor.by, 'update.publisher-key.propose', res(nationId), 'ok', `${keyId} · checked: ${checkedWith.slice(0, 120)} · waiting for a different official`);
  return structuredClone(k);
}

/** A different official confirms: the key is trusted from now; an earlier trusted key is retired (it still verifies what it signed). */
export function confirmPublisherKey(nationId: string, id: string, actor: TrustActor, now = new Date()): PublisherKey | { error: string; status: number } {
  lapse(now);
  const k = db().keys.find(x => x.id === id && x.nationId === nationId);
  if (!k || k.state !== 'proposed') return fail('No key with that number is waiting (a proposal lapses after the waiting period)', 404);
  const same = dualControlRefusal(k.proposed, { by: actor.by, ...(actor.byId ? { byId: actor.byId } : {}) });
  if (same) return fail(same, 403);
  for (const o of db().keys) if (o.nationId === nationId && o.state === 'trusted') { o.state = 'retired'; o.retiredAt = now.toISOString(); }
  k.state = 'trusted';
  k.confirmed = { by: actor.by, ...(actor.byId ? { byId: actor.byId } : {}), at: now.toISOString(), independence: independenceOf(k.proposed.byId, actor.byId) };
  recordAudit(actor.by, 'update.publisher-key.trust', res(nationId), 'ok', `${k.keyId} · proposed by ${k.proposed.by}, confirmed by ${actor.by} (${k.confirmed.independence})`);
  return structuredClone(k);
}

/** Withdraw a waiting proposal, or revoke a trusted or retired key at once (one official: it only takes trust away). */
export function revokePublisherKey(nationId: string, id: string, reason: unknown, actor: TrustActor, now = new Date()): PublisherKey | { error: string; status: number } {
  const k = db().keys.find(x => x.id === id && x.nationId === nationId);
  if (!k) return fail('No such key', 404);
  const why = typeof reason === 'string' ? reason.trim().slice(0, 300) : '';
  if (!why) return fail('Say why the key is no longer trusted');
  if (k.state === 'proposed') { k.state = 'withdrawn'; recordAudit(actor.by, 'update.publisher-key.withdraw', res(nationId), 'ok', `${k.keyId} · ${why}`); return structuredClone(k); }
  if (k.state !== 'trusted' && k.state !== 'retired') return fail(`The key is ${k.state}`, 409);
  k.state = 'revoked';
  k.revoked = { by: actor.by, at: now.toISOString(), reason: why };
  recordAudit(actor.by, 'update.publisher-key.revoke', res(nationId), 'ok', `${k.keyId} · ${why}`);
  return structuredClone(k);
}

/** The keys a nation's verification reads: trusted, retired (with when) and revoked (never verifying). */
export function trustedKeysFor(nationId: string): TrustedKey[] {
  return db().keys.filter(k => k.nationId === nationId && ['trusted', 'retired', 'revoked'].includes(k.state) && k.confirmed).map(k => ({
    keyId: k.keyId, publicKeyPem: k.publicKeyPem, trustedFrom: k.confirmed!.at, ...(k.retiredAt ? { retiredAt: k.retiredAt } : {}), ...(k.revoked ? { revokedAt: k.revoked.at } : {}),
  }));
}

/** Proposals waiting for a second official (the onboarding hub). */
export const waitingPublisherKeys = (now = new Date()): PublisherKey[] => { lapse(now); return db().keys.filter(k => k.state === 'proposed').map(k => structuredClone(k)); };
