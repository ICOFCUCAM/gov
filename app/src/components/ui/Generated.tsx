'use client';

// Generated figures on console screens (lib/twin/generated.ts): shown with
// their marker in demo and training, "Not connected" in production. One
// mechanism for every console surface:
//
//   useGenerated()       the rule for this installation, for a single value
//                        (`shownValue(g, v)`) or a tone (`shownTone(g, t)`)
//   <GeneratedFold>      a block of generated figures: shown in demo and
//                        training; in production folded under "Not connected",
//                        rendered only when an official opens it as a
//                        simulation, so links and actions stay reachable
//   <GeneratedStrip>     a strip of headline tiles: one marker for the strip
//                        in demo and training, the fold in production
//   <GeneratedText>      one generated value in running text
//
// `Panel signal="sample" | "simulated"` (components/features/SituationRoom.tsx)
// folds its body through GeneratedFold. The agency apps' SimulatedView
// (apps/_shared/RegisterRecords.tsx) and the executive posture
// (lib/gov/executive-posture.ts) follow the same rule.

import * as React from 'react';
import { useSamplesAllowed } from '@/lib/ops/mode-context';
import { generatedPolicy, isGenerated, NOT_CONNECTED, NOT_CONNECTED_REASON, type GeneratedPolicy } from '@/lib/twin/generated';
import { REFERENCE_MODEL, type SignalKind } from '@/lib/twin/signal';
import { SignalTag } from './SignalTag';

export { shownValue, shownTone, isGenerated, NOT_CONNECTED } from '@/lib/twin/generated';

/** Why figures show inside a fold an official opened on a production installation. */
export const OPENED_AS_SIMULATION = 'Opened as a simulation on a production installation; not this nation\'s figures';

// Inside a fold an official opened on purpose, generated figures show, marked Simulation.
const Revealed = React.createContext(false);

/** Marks its children as opened on request as a simulation (GeneratedFold, the agency apps' SimulatedView). */
export function GeneratedReveal({ children }: { children?: React.ReactNode }) {
  return <Revealed.Provider value>{children}</Revealed.Provider>;
}

// Inside a block that already carries the marker (a Sample panel, a marked strip), tiles need not repeat it.
const Marked = React.createContext(false);

/** Children sit under a marker their parent shows (a generated panel's header tag). */
export function GeneratedMarked({ children }: { children?: React.ReactNode }) {
  return <Marked.Provider value>{children}</Marked.Provider>;
}

/** Whether a parent block already shows the marker for these figures. */
export const useMarkedByParent = (): boolean => React.useContext(Marked);

/** The rule for generated figures on this installation (demo and training: shown, marked; production: not connected). */
export function useGenerated(kind: 'sample' | 'simulated' = 'sample', src: string = REFERENCE_MODEL): GeneratedPolicy {
  const samples = useSamplesAllowed();
  const revealed = React.useContext(Revealed);
  if (!samples && revealed) return { show: true, kind: 'simulated', src: OPENED_AS_SIMULATION };
  return generatedPolicy(samples, kind, src);
}

/**
 * A block of generated figures. Demo and training: the children as they are
 * (the caller marks them, e.g. a panel's header tag), or under a marker line
 * with `marked`. Production: folded under "Not connected"; opened, the
 * children render as a simulation.
 */
export function GeneratedFold({ kind = 'sample', source = REFERENCE_MODEL, what = 'These figures', note, marked = false, className = '', children }: {
  kind?: 'sample' | 'simulated'; source?: string;
  /** What is folded, in words ("These figures", "Work items"). */
  what?: string;
  /** The marker line's words in demo and training (default: generated by the reference model). */
  note?: string;
  /** Show a marker line above the children in demo and training. */
  marked?: boolean;
  className?: string;
  children?: React.ReactNode;
}) {
  const g = useGenerated(kind, source);
  const [open, setOpen] = React.useState(false);
  if (g.show) {
    if (!marked) return <>{children}</>;
    return (
      <div className={className}>
        <div className="mb-1 flex items-center gap-1.5 text-[9px] text-ink-muted">
          <SignalTag kind={g.kind} source={g.src} />
          <span>{note ?? `${g.kind === 'simulated' ? 'Simulation' : 'Generated by the reference model'}; not this nation's figures.`}</span>
        </div>
        <GeneratedMarked>{children}</GeneratedMarked>
      </div>
    );
  }
  return (
    <details data-generated="folded" className={`rounded-[3px] border border-dashed border-line ${className}`} onToggle={e => setOpen((e.currentTarget as HTMLDetailsElement).open)}>
      <summary className="focus-ring flex cursor-pointer items-center gap-1.5 px-2 py-1 text-[10px] text-ink-soft">
        <SignalTag kind="unavailable" source={NOT_CONNECTED_REASON} />
        <span>{what}: no source connected on this installation. Open to see them as a simulation.</span>
      </summary>
      {open ? <div className="p-2"><GeneratedReveal><GeneratedMarked>{children}</GeneratedMarked></GeneratedReveal></div> : null}
    </details>
  );
}

/** A strip of generated headline tiles: one marker in demo and training, folded in production. */
export function GeneratedStrip({ kind = 'sample', source = REFERENCE_MODEL, what = 'Headline figures', note, className = '', children }: {
  kind?: 'sample' | 'simulated'; source?: string; what?: string; note?: string; className?: string; children?: React.ReactNode;
}) {
  return <GeneratedFold kind={kind} source={source} what={what} note={note} marked className={className}>{children}</GeneratedFold>;
}

/**
 * What one headline tile shows: its value and marker, or "Not connected".
 * `kind` is where the value comes from (default: generated, `sample`); a
 * record, observation or official statement is shown as it is, unmarked.
 */
export function useTile(value: React.ReactNode, kind: SignalKind = 'sample', source?: string, tag?: React.ReactNode): { value: React.ReactNode; folded: boolean; marker: React.ReactNode } {
  const g = useGenerated(kind === 'simulated' ? 'simulated' : 'sample', source ?? REFERENCE_MODEL);
  const parent = useMarkedByParent();
  if (isGenerated(kind) && !g.show) return { value: NOT_CONNECTED, folded: true, marker: <SignalTag kind="unavailable" source={g.src} /> };
  if (tag !== undefined) return { value, folded: false, marker: tag };
  if (!isGenerated(kind)) return { value, folded: false, marker: <SignalTag kind={kind} source={source} /> };
  return { value, folded: false, marker: parent ? null : <SignalTag kind={g.kind} source={g.src} /> };
}

/** One generated value in running text: the value and its marker, or "Not connected". */
export function GeneratedText({ kind = 'sample', source = REFERENCE_MODEL, children }: { kind?: 'sample' | 'simulated'; source?: string; children?: React.ReactNode }) {
  const g = useGenerated(kind, source);
  return g.show
    ? <span className="inline-flex items-center gap-1">{children}<SignalTag kind={g.kind} source={g.src} /></span>
    : <SignalTag kind="unavailable" source={g.src} />;
}
