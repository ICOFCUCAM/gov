'use client';

// One panel's generated figures. Since step I0.1 there is one rule for every
// generated figure on a console (lib/twin/generated.ts, components/ui/
// Generated.tsx); SampleFold and SampleTag are the per-panel entry points to
// it, kept so their callers stay as they are:
//   demo and training  the panel as it is, its marker saying Sample
//   production         folded under "Not connected", rendered only when an
//                      official opens it, then marked Simulation
// The mode comes from the root layout (lib/ops/mode-context.tsx); outside the
// provider it is production, so nothing generated reads as the nation's. A
// caller may name the mode (`mode`) where it knows it better.

import * as React from 'react';
import { SignalTag } from '@/components/ui/SignalTag';
import { GeneratedFold, useGenerated } from '@/components/ui/Generated';
import { InstallationModeProvider } from '@/lib/ops/mode-context';
import type { InstallationMode } from '@/lib/ops/mode';

// A caller that names the mode reads the rule under it; otherwise the layout's.
const InMode = ({ mode, children }: { mode?: InstallationMode; children: React.ReactNode }) =>
  mode ? <InstallationModeProvider mode={mode}>{children}</InstallationModeProvider> : <>{children}</>;

function Tag({ source, className }: { source: string; className?: string }) {
  const g = useGenerated('sample', source);
  return <SignalTag kind={g.kind} source={g.src} className={className} />;
}

/** The marker for a generated panel: Sample where samples are allowed, Not connected in production (the one rule). */
export function SampleTag({ source, mode, className }: { source: string; mode?: InstallationMode; className?: string }) {
  return <InMode mode={mode}><Tag source={source} className={className} /></InMode>;
}

/**
 * Generated content of one panel, through GeneratedFold. `what` names it in
 * the folded line ("Regional figures"); `source` says where the figures come
 * from. In demo and training a short Sample line stands above it, unless the
 * panel's own title already carries a SampleTag (`marked`).
 */
export function SampleFold({ what, source, mode, marked = false, children, className = '' }: {
  what: string; source: string; mode?: InstallationMode; marked?: boolean; children?: React.ReactNode; className?: string;
}) {
  return (
    <InMode mode={mode}>
      <GeneratedFold kind="sample" source={source} what={what} marked={!marked} className={className}
        note={`${what}: generated by a simulation engine, not this nation's records.`}>
        {children}
      </GeneratedFold>
    </InMode>
  );
}
