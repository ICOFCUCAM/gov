// One generated panel: Sample in demo and training, folded to Not connected
// (and not rendered) in production, and production outside the mode provider.
import { describe, it, expect } from 'vitest';
import * as React from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import { SampleFold, SampleTag } from './SampleFold';
import { InstallationModeProvider } from '@/lib/ops/mode-context';
import { GeneratedFold, GeneratedReveal } from './Generated';
import { NOT_CONNECTED_REASON } from '@/lib/twin/generated';
import type { InstallationMode } from '@/lib/ops/mode';

const Provider = InstallationModeProvider as React.FC<{ mode: InstallationMode; children?: React.ReactNode }>;

const FIGURE = 'Regional figure 4,812';
const fold = (mode: InstallationMode | null, marked = false) => {
  const el = React.createElement(SampleFold, { what: 'Regional status', source: 'Ministry operations model', marked }, React.createElement('span', null, FIGURE));
  return renderToStaticMarkup(mode ? React.createElement(Provider, { mode }, el) : el);
};

describe('SampleFold', () => {
  it('in production folds the panel under Not connected and renders none of its figures', () => {
    for (const html of [fold('production'), fold(null)]) {
      expect(html).toContain('Not connected');
      expect(html).toContain('<details');
      expect(html).not.toContain(FIGURE);
    }
  });

  it('in demo and training shows the panel with a Sample marker (or the panel\'s own, when marked)', () => {
    for (const mode of ['demo', 'training'] as const) {
      const html = fold(mode);
      expect(html).toContain(FIGURE);
      expect(html).toContain('Sample');
      expect(html).not.toContain('<details');
    }
    expect(fold('demo', true)).toBe(`<span>${FIGURE}</span>`);
  });

  it('SampleTag says Sample where samples are allowed and Not connected in production', () => {
    const tag = (mode: InstallationMode) => renderToStaticMarkup(React.createElement(Provider, { mode }, React.createElement(SampleTag, { source: 'x' })));
    expect(tag('demo')).toContain('Sample');
    expect(tag('production')).toContain('Not connected');
  });

  it('is the one rule: the same fold, wording and marker as GeneratedFold (lib/twin/generated.ts)', () => {
    const inMode = (mode: InstallationMode, el: React.ReactElement) => renderToStaticMarkup(React.createElement(Provider, { mode }, el));
    const generated = React.createElement(GeneratedFold, { kind: 'sample', source: 'Ministry operations model', what: 'Regional status', marked: true, note: 'Regional status: generated by a simulation engine, not this nation\'s records.' }, React.createElement('span', null, FIGURE));
    for (const mode of ['production', 'demo', 'training'] as const) expect(fold(mode)).toBe(inMode(mode, generated));
    // Production: the reason is the rule's, the summary the rule's words.
    expect(fold('production')).toContain(NOT_CONNECTED_REASON.replace(/'/g, '&#x27;'));
    const tag = renderToStaticMarkup(React.createElement(Provider, { mode: 'production' }, React.createElement(SampleTag, { source: 'x' })));
    expect(tag).toContain(NOT_CONNECTED_REASON.replace(/'/g, '&#x27;'));
  });

  it('opened on purpose in production, its marker says Simulation, never Sample', () => {
    const tag = renderToStaticMarkup(React.createElement(Provider, { mode: 'production' }, React.createElement(GeneratedReveal, null, React.createElement(SampleTag, { source: 'x' }))));
    expect(tag).toContain('Simulation');
    expect(tag).not.toContain('Not connected');
  });

  it('a mode named by the caller is honoured', () => {
    const tag = renderToStaticMarkup(React.createElement(SampleTag, { source: 'x', mode: 'demo' }));
    expect(tag).toContain('Sample');
  });
});
